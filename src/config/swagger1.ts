  '',
  '---',
  '## Frontend integration guide',
  '',
  '### 0. Auth (same as the rest of the API)',
  'Every `/campaigns` call needs `Authorization: Bearer <access_token>` and `x-api-key: <key>`.',
  'POST / PATCH / DELETE also need `x-csrf-token` (the `csrf_token` returned by `POST /auth/login`).',
  'In this page: run **Auth → POST /auth/login**, then click **Authorize** and paste the token, API key and CSRF token.',
  '',
  '```js',
  "const api = axios.create({ baseURL: 'https://api.succesly.in/api/v1', withCredentials: true });",
  'api.interceptors.request.use(cfg => {',
  '  cfg.headers.Authorization   = `Bearer ${accessToken}`;',
  "  cfg.headers['x-api-key']    = API_KEY;",
  "  if (cfg.method !== 'get') cfg.headers['x-csrf-token'] = csrfToken;",
  '  return cfg;',
  '});',
  '```',
  '',
  '### 1. Create-campaign form',
  '1. Load the industry dropdown once: `GET /campaigns/industry-types` → `[{ value, label }]`.',
  '2. Fields: name, industry, destination URL, `utm_source` / `utm_medium` / `utm_campaign` (required),',
  '   `utm_term`, `utm_content`, `utm_id`, `utm_source_platform` (optional), up to 5 custom params, short URL name, dates, fallback URL.',
  '3. **Short URL name input** — show the domain as a suffix: `[ iphone17-diwali ].succesly.in`.',
  '   Lower-case the value as the user types and check it live (debounced):',
  '',
  '```js',
  'const checkSlug = debounce(async (slug) => {',
  '  if (slug.length < 3) return;',
  "  const { data } = await api.get('/campaigns/check-slug', { params: { slug } });",
  '  setSlugState(data.data);   // { available, reason, suggestions }',
  '}, 400);',
  '```',
  '   - `available: true` → green tick',
  '   - `available: false` → show `reason` ("already taken — please change the short URL name") and render `suggestions` as chips that fill the input on click',
